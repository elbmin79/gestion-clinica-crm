// Run after invitation-smoke.mjs setup, against a running local production build.
// PLAYWRIGHT_MODULE can point at an existing Playwright installation.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
import { createClient } from '@supabase/supabase-js';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fixture = JSON.parse(await readFile(new URL('../.invitation-qa/fixture.json',import.meta.url),'utf8'));
const origin = process.env.TEST_APP_URL || 'http://127.0.0.1:3000';
const client = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const browser = await chromium.launch({ headless:true });
const context = await browser.newContext({ viewport:{width:1440,height:1000} });
const page = await context.newPage();
const browserErrors = [];
page.on('pageerror',error => browserErrors.push(error.message));
page.on('console',message => { if (message.type() === 'error') console.log('Browser error:',message.text()); });
await mkdir(new URL('../.invitation-qa/',import.meta.url),{recursive:true});
try {
  await page.goto(`${origin}/auth/callback?token_hash=${fixture.tokenHash}&type=${fixture.verificationType || 'invite'}&next=${encodeURIComponent(`/accept-invite?id=${fixture.invitationId}`)}`);
  await page.getByRole('heading',{name:'Crea tu contraseña',exact:true}).waitFor({timeout:20000});
  const assertCenteredLogo = async () => {
    const card = await page.locator('.auth-card').boundingBox();
    const logo = await page.locator('.auth-brand').boundingBox();
    assert.ok(Math.abs(card.x + card.width / 2 - logo.x - logo.width / 2) < 1,'logo must be centered in the card');
  };
  await assertCenteredLogo();
  assert.equal((await client.from('clinic_memberships').select('user_id').eq('clinic_id',fixture.clinicId).eq('user_id',fixture.userId)).data.length,0);
  await page.screenshot({path:new URL('../.invitation-qa/password-desktop.png',import.meta.url).pathname.replace(/^\/([A-Z]:)/,'$1'),fullPage:true});
  await page.goto(`${origin}/agenda`);
  await page.waitForURL(/accept-invite/);
  console.log('PASS: invitation verifies email; password setup is mandatory; no membership exists yet.');
  await page.getByLabel('Nueva contraseña',{exact:true}).fill(fixture.password);
  await page.getByLabel('Repite la contraseña',{exact:true}).fill('wrong-password');
  await page.getByRole('button',{name:'Crear contraseña y entrar'}).click();
  await page.getByRole('alert').filter({hasText:'Las contraseñas no coinciden.'}).waitFor();
  await page.getByLabel('Nueva contraseña',{exact:true}).fill(fixture.password);
  await page.getByLabel('Repite la contraseña',{exact:true}).fill(fixture.password);
  await page.setViewportSize({width:390,height:844});
  await assertCenteredLogo();
  await page.screenshot({path:new URL('../.invitation-qa/password-mobile.png',import.meta.url).pathname.replace(/^\/([A-Z]:)/,'$1'),fullPage:true});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),'password form must not overflow mobile');
  await page.getByRole('button',{name:'Crear contraseña y entrar'}).click();
  await page.waitForURL(url => url.pathname === '/' && url.searchParams.get('clinic') === fixture.clinicId,{timeout:20000});
  const membership = await client.from('clinic_memberships').select('role,permissions').eq('clinic_id',fixture.clinicId).eq('user_id',fixture.userId).single();
  assert.equal(membership.error,null); assert.equal(membership.data.role,'clinician');
  const auth = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL,process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,{auth:{persistSession:false}});
  assert.equal((await auth.auth.signInWithPassword({email:fixture.email,password:fixture.password})).error,null);
  console.log('PASS: password mismatch handled; saving password activates correct permissions and enters CRM without another login/email.');
  await page.goto(`${origin}/equipo`);
  await page.waitForTimeout(1000);
  assert.equal(await page.getByRole('heading',{name:'Invitar persona',exact:true}).count(),0);
  console.log('PASS: clinician does not see invitation controls.');
  const adminContext = await browser.newContext({viewport:{width:1440,height:1000}});
  const adminPage = await adminContext.newPage();
  await adminPage.goto(`${origin}/login`);
  await adminPage.getByLabel('Correo electrónico',{exact:true}).fill(fixture.adminEmail);
  await adminPage.locator('input[name="password"]').fill(fixture.password);
  await adminPage.getByRole('button',{name:/Entrar|Iniciar sesión/}).click();
  await adminPage.waitForURL(origin+'/',{timeout:20000});
  await adminPage.goto(`${origin}/equipo`);
  await adminPage.getByRole('heading',{name:'Invitar persona',exact:true}).waitFor();
  await adminPage.getByLabel('Correo electrónico',{exact:true}).fill('new-teammate@example.invalid');
  await adminPage.getByRole('button',{name:'Revisar invitación',exact:true}).click();
  await adminPage.getByRole('dialog',{name:'Revisar invitación'}).waitFor();
  await adminPage.getByRole('dialog').getByRole('button',{name:'Cancelar',exact:true}).click();
  await adminPage.locator('.clinic-access-panel').screenshot({path:new URL('../.invitation-qa/admin-desktop.png',import.meta.url).pathname.replace(/^\/([A-Z]:)/,'$1')});
  await adminPage.setViewportSize({width:390,height:844});
  await adminPage.reload();
  await adminPage.getByRole('heading',{name:'Invitar persona',exact:true}).waitFor();
  await adminPage.locator('.clinic-invite-form').scrollIntoViewIfNeeded();
  await adminPage.screenshot({path:new URL('../.invitation-qa/admin-mobile.png',import.meta.url).pathname.replace(/^\/([A-Z]:)/,'$1'),fullPage:true});
  assert.ok(await adminPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth),'admin panel must not overflow mobile');
  console.log('PASS: admin invitation review, role/permission editor and responsive panel; no email was sent.');
  // Verify an already-registered account accepts access without a password reset.
  const existingEmail = `codex-invite-existing-${randomUUID()}@example.invalid`;
  const existing = await client.auth.admin.createUser({email:existingEmail,password:fixture.password,email_confirm:true});
  assert.equal(existing.error,null);
  fixture.userIds.push(existing.data.user.id);
  await writeFile(new URL('../.invitation-qa/fixture.json',import.meta.url),JSON.stringify(fixture),'utf8');
  const prepared = await client.rpc('prepare_clinic_invitation',{p_clinic:fixture.clinicId,p_inviter:fixture.adminId,p_email:existingEmail,p_role:'receptionist',p_permissions:{'agenda.create':true}});
  assert.equal(prepared.error,null); assert.equal(prepared.data.requires_password,false);
  const existingLink = await client.auth.admin.generateLink({type:'magiclink',email:existingEmail});
  assert.equal(existingLink.error,null);
  const existingContext = await browser.newContext();
  const existingPage = await existingContext.newPage();
  await existingPage.goto(`${origin}/auth/callback?token_hash=${existingLink.data.properties.hashed_token}&type=email&next=${encodeURIComponent(`/accept-invite?id=${prepared.data.id}`)}`);
  await existingPage.getByRole('heading',{name:'Acepta tu invitación',exact:true}).waitFor();
  assert.equal(await existingPage.locator('input[type="password"]').count(),0);
  await existingPage.getByRole('button',{name:'Aceptar invitación y entrar'}).click();
  await existingPage.waitForURL(url => url.pathname==='/' && url.searchParams.get('clinic')===fixture.clinicId);
  assert.equal((await auth.auth.signInWithPassword({email:existingEmail,password:fixture.password})).error,null);
  console.log('PASS: existing-account invitation activates the clinic and preserves its original password.');
  await existingContext.close();
  assert.deepEqual(browserErrors,[]);
  await adminContext.close();
} catch (error) {
  console.log('Browser state:', new URL(page.url()).pathname, await page.locator('body').innerText());
  throw error;
} finally { await browser.close(); }
